// Bakes the crumpled sheet for the opening into src/opening/paperMesh.ts, so the visitor's browser
// never has to relax the mesh itself. The folding method follows LeiBox's Crumpled Paper component
// (https://leibox.pantoria.cn/docs/animations/crumpled-paper, design reference by Matt:
// https://x.com/insporadesign/status/2113586239110828465/video/1), cut down to one blank sheet.
// Run with: node scripts/bake-opening-paper.mjs
import { writeFileSync } from 'node:fs';

const COLS = 32;
const ROWS = 32;
const clamp = (value, low, high) => Math.min(high, Math.max(low, value));
function random(seed) {
  return () => {
    seed |= 0;
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t ^= t + Math.imul(t ^ (t >>> 7), 61 | t);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = random(54);
const points = [];
for (let y = 0; y <= ROWS; y++) {
  for (let x = 0; x <= COLS; x++) {
    const u = (x + (x && x < COLS ? (rand() - 0.5) * 0.7 : 0)) / COLS;
    const v = (y + (y && y < ROWS ? (rand() - 0.5) * 0.7 : 0)) / ROWS;
    const cu = u - 0.5;
    const cv = v - 0.5;
    const rho = Math.hypot(cu, cv);
    const angle = rho * 4.82;
    const fold = Math.sin(u * 31 + v * 10 + 1) * Math.sin(v * 28 - u * 8) * 0.12 + Math.sin(u * 65 - v * 23) * 0.048;
    const r = 1 + fold * 0.65;
    const closed = [Math.sin(angle) * (rho ? cu / rho : 0) * 86 * r, Math.sin(angle) * (rho ? cv / rho : 0) * 92 * r, Math.cos(angle) * 76 * r];
    closed[0] += Math.sin(v * 18 + 2) * 5.5;
    closed[1] += Math.sin(u * 17 + 1) * 4;
    const front = Math.max(0, Math.cos(angle * 0.65));
    closed[2] += (Math.sin(v * 25 + Math.sin(u * 12) * 1.8) * 17 + Math.sin(u * 34 - v * 7) * 9) * front;
    closed[0] += Math.sin(v * 25 + u * 15) * 5 * front;
    closed[1] += Math.sin(u * 25 - v * 11) * 5 * front;
    points.push({ closed, u, v, sheet: [(u - 0.5) * 340, (v - 0.5) * 340], crease: clamp((rand() - 0.5) * 2, -1, 1) });
  }
}

// Keep the sheet's edge lengths while compacting it, so the spare area buckles into folds rather than
// being pressed onto a smooth ball.
const constraints = [];
const seen = new Set();
const edge = (a, b) => {
  const key = Math.min(a, b) * points.length + Math.max(a, b);
  if (seen.has(key)) return;
  seen.add(key);
  const [p, q] = [points[a], points[b]];
  constraints.push([a, b, Math.hypot(p.sheet[0] - q.sheet[0], p.sheet[1] - q.sheet[1]) * 1.48]);
};
for (let y = 0; y < ROWS; y++) {
  for (let x = 0; x < COLS; x++) {
    const a = y * (COLS + 1) + x;
    const [b, c, d] = [a + 1, a + COLS + 1, a + COLS + 2];
    edge(a, b);
    edge(a, c);
    edge(b, d);
    edge(c, d);
    if ((x + y) % 2) edge(a, d);
    else edge(b, c);
  }
}
for (let step = 0; step < 260; step++) {
  for (let j = 0; j < constraints.length; j++) {
    const [a, b, length] = constraints[step % 2 ? constraints.length - 1 - j : j];
    const [p, q] = [points[a].closed, points[b].closed];
    const [dx, dy, dz] = [q[0] - p[0], q[1] - p[1], q[2] - p[2]];
    const distance = Math.hypot(dx, dy, dz) || 1;
    const t = ((distance - length) / distance) * 0.42;
    p[0] += dx * t;
    p[1] += dy * t;
    p[2] += dz * t;
    q[0] -= dx * t;
    q[1] -= dy * t;
    q[2] -= dz * t;
  }
  for (const { closed: p } of points) {
    const r = Math.hypot(p[0] / 92, p[1] / 96, p[2] / 84);
    if (r > 1) {
      const t = (1 / r - 1) * 0.68;
      p[0] += p[0] * t;
      p[1] += p[1] * t;
      p[2] += p[2] * t;
    }
  }
}

// closed xyz in hundredths of a pixel, then uv and the crease height scaled to the int16 range.
const values = new Int16Array(points.length * 6);
points.forEach((point, index) => {
  values.set(
    [...point.closed.map((value) => Math.round(value * 100)), Math.round(point.u * 32767), Math.round(point.v * 32767), Math.round(point.crease * 32767)],
    index * 6,
  );
});
const base64 = Buffer.from(values.buffer).toString('base64');
writeFileSync(
  'src/opening/paperMesh.ts',
  `// Generated by scripts/bake-opening-paper.mjs. Do not edit by hand.\nexport const PAPER_COLS = ${COLS};\nexport const PAPER_ROWS = ${ROWS};\nexport const PAPER_MESH = "${base64}";\n`,
);
console.log({ vertices: points.length, base64: base64.length });
